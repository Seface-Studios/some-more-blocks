  private static BlockItemId create(final String blockName, final String itemName) {
    return BlockItemId.create(SomeMoreBlocks.id(blockName), SomeMoreBlocks.id(itemName));
  }

  private static BlockItemId create(final String name) {
    Identifier id = SomeMoreBlocks.id(name);
    return BlockItemId.create(id, id);
  }

  private static ColorCollection<@NotNull BlockItemId> createColored(final String baseBlockName) {
    return ColorCollection.prefixWithColor(ColorCollection.create(baseBlockName)).map(SMBBlockItemIds::create);
  }

  private static WeatheringCopperCollection<@NotNull BlockItemId> createWeathering(final String baseBlockName) {
    return WeatheringCopperCollection.prefixWithState(WeatheringCopperCollection.create(baseBlockName)).map(SMBBlockItemIds::create);
  }
